"""RESTClientObject Content-Type defaults.

Generated ``create_*`` and ``delete_*`` serializers accept ``_content_type``
but do not emit a header when the OpenAPI operation consumes ``*/*``. Those
files are regenerated by ``scripts/update-client.sh``, so the default lives
in ``kubernetes/client/rest.py`` (and ``scripts/rest_client_patch.diff``).
``_headers`` is the supported override. ``kubernetes.aio`` already defaults
the header in its generated REST client and is not patched here.

``kubernetes/test`` is the OpenAPI-generated suite. This file sits with the
other hand-written REST tests (``keepalive_test.py``, ``retry_test.py``) so
``tox -e py`` collects it.
"""

from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import threading
import unittest
from unittest import mock

import urllib3

from kubernetes.client import (
    ApiClient,
    BatchV1Api,
    Configuration,
    V1DeleteOptions,
)
from kubernetes.client.rest import RESTClientObject


JOB_BODY = {
    'apiVersion': 'batch/v1',
    'kind': 'Job',
    'metadata': {'name': 'x'},
    'spec': {
        'template': {
            'spec': {
                'containers': [{'name': 'c', 'image': 'i'}],
            },
        },
    },
}


def _sent(rest_client):
    kwargs = rest_client.pool_manager.request.call_args.kwargs
    return kwargs.get('headers') or {}, kwargs.get('body')


class RESTClientObjectContentTypeTest(unittest.TestCase):
    def setUp(self):
        self.rest_client = RESTClientObject(Configuration())
        self.rest_client.pool_manager = mock.Mock()
        response = urllib3.HTTPResponse(
            body=b'{}', status=200, reason='OK')
        self.rest_client.pool_manager.request.return_value = response

    def _request(self, method, headers=None, body=None, post_params=None):
        self.rest_client.request(
            method,
            'http://127.0.0.1/api',
            headers=headers,
            body=body,
            post_params=post_params,
        )
        return _sent(self.rest_client)

    def test_json_body_without_header_sets_application_json(self):
        caller = {'Accept': 'application/json'}

        headers, body = self._request('POST', headers=caller, body={'a': 1})

        self.assertEqual('application/json', headers['Content-Type'])
        self.assertEqual('{"a": 1}', body)
        self.assertEqual({'Accept': 'application/json'}, caller)
        self.assertIsNot(headers, caller)

    def test_missing_body_does_not_set_content_type(self):
        for method in ('POST', 'PUT', 'PATCH', 'OPTIONS', 'DELETE'):
            with self.subTest(method=method):
                self.rest_client.pool_manager.request.reset_mock()
                headers, body = self._request(
                    method, headers={'Accept': 'json'})

                self.assertNotIn('Content-Type', headers)
                self.assertIsNone(body)
                self.assertNotIn('content-type', headers)

    def test_get_and_head_do_not_set_content_type(self):
        for method in ('GET', 'HEAD'):
            with self.subTest(method=method):
                self.rest_client.pool_manager.request.reset_mock()
                headers, body = self._request(
                    method, headers={'Accept': 'json'})

                self.assertNotIn('Content-Type', headers)
                self.assertIsNone(body)

    def test_lowercase_content_type_is_not_duplicated(self):
        caller = {'content-type': 'application/merge-patch+json'}

        headers, body = self._request('POST', headers=caller, body={'a': 1})

        names = [key for key in headers if key.lower() == 'content-type']
        self.assertEqual(['content-type'], names)
        self.assertEqual(
            'application/merge-patch+json', headers['content-type'])
        self.assertEqual('{"a": 1}', body)
        self.assertEqual(caller, headers)

    def test_explicit_json_content_type_is_preserved(self):
        caller = {'Content-Type': 'application/json; charset=utf-8'}

        headers, body = self._request('PUT', headers=caller, body={'a': 1})

        self.assertEqual(
            'application/json; charset=utf-8', headers['Content-Type'])
        self.assertEqual('{"a": 1}', body)
        self.assertIs(headers, caller)

    def test_json_patch_list_keeps_json_patch_media_type(self):
        operations = [{'op': 'replace', 'path': '/a', 'value': 1}]
        caller = {'Content-Type': 'application/json-patch+json'}

        headers, body = self._request('PATCH', headers=caller, body=operations)

        self.assertEqual(
            'application/json-patch+json', headers['Content-Type'])
        self.assertEqual(operations, json.loads(body))

    def test_object_patch_still_selects_strategic_merge(self):
        caller = {'content-type': 'application/json-patch+json'}

        headers, body = self._request(
            'PATCH', headers=caller, body={'data': {'key': 'value'}},
        )

        self.assertEqual(
            'application/strategic-merge-patch+json',
            headers['content-type'],
        )
        self.assertNotIn('Content-Type', headers)
        self.assertEqual({'data': {'key': 'value'}}, json.loads(body))
        self.assertIs(headers, caller)

    def test_structured_yaml_keeps_its_media_type(self):
        caller = {'Content-Type': 'application/apply-patch+yaml'}

        headers, body = self._request('PATCH', headers=caller, body={'a': 1})

        self.assertEqual(
            'application/apply-patch+yaml', headers['Content-Type'])
        self.assertEqual('{"a": 1}', body)

    def test_plain_text_body_is_not_relabeled_json(self):
        caller = {'Content-Type': 'text/plain'}

        headers, body = self._request('POST', headers=caller, body='hello')

        self.assertEqual('text/plain', headers['Content-Type'])
        self.assertEqual('hello', body)

    def test_untyped_string_body_is_json(self):
        headers, body = self._request('POST', body='hello')

        self.assertEqual('application/json', headers['Content-Type'])
        self.assertEqual('"hello"', body)

    def test_form_and_multipart_are_not_relabeled_json(self):
        form = {'Content-Type': 'application/x-www-form-urlencoded'}
        headers, body = self._request(
            'POST', headers=form, post_params=[('a', 'b')],
        )
        self.assertEqual(
            'application/x-www-form-urlencoded', headers['Content-Type'])
        self.assertIsNone(body)

        multipart = {'Content-Type': 'multipart/form-data'}
        headers, body = self._request(
            'POST', headers=multipart, post_params=[('file', 'data')],
        )
        self.assertNotIn('Content-Type', headers)
        self.assertIsNone(body)


class _RecordingHandler(BaseHTTPRequestHandler):
    def do_POST(self):
        self._record()

    def do_DELETE(self):
        self._record()

    def _record(self):
        length = int(self.headers.get('Content-Length') or 0)
        self.server.requests.append({
            'method': self.command,
            'path': self.path,
            'content_type': self.headers.get('Content-Type'),
            'content_types': self.headers.get_all('Content-Type'),
            'body': self.rfile.read(length),
        })
        payload = self.server.response_body
        self.send_response(self.server.response_status)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, format, *args):
        pass


class BatchJobContentTypeTest(unittest.TestCase):
    def setUp(self):
        self.server = ThreadingHTTPServer(('127.0.0.1', 0), _RecordingHandler)
        self.server.requests = []
        self.server.response_body = b'{}'
        self.server.response_status = 201
        self.thread = threading.Thread(target=self.server.serve_forever)
        self.thread.start()
        self.api_client = ApiClient(Configuration(
            host='http://127.0.0.1:%d' % self.server.server_port,
            proxy='',
            no_proxy='',
        ))
        self.api = BatchV1Api(self.api_client)

    def tearDown(self):
        self.server.shutdown()
        self.thread.join()
        self.server.server_close()
        self.api_client.close()

    def test_create_namespaced_job_sends_json_content_type(self):
        created = self.api.create_namespaced_job(namespace='n', body=JOB_BODY)

        self.assertIsNotNone(created)
        request = self.server.requests[-1]
        self.assertEqual('POST', request['method'])
        self.assertEqual('/apis/batch/v1/namespaces/n/jobs', request['path'])
        self.assertEqual(['application/json'], request['content_types'])
        self.assertEqual(JOB_BODY, json.loads(request['body']))

    def test_delete_namespaced_job_with_options_sends_json_content_type(self):
        self.server.response_status = 200
        options = V1DeleteOptions(
            propagation_policy='Background',
            grace_period_seconds=5,
        )

        self.api.delete_namespaced_job(
            name='x', namespace='n', body=options,
        )

        request = self.server.requests[-1]
        self.assertEqual('DELETE', request['method'])
        self.assertEqual(
            '/apis/batch/v1/namespaces/n/jobs/x', request['path'],
        )
        self.assertEqual(['application/json'], request['content_types'])
        self.assertEqual(
            {'propagationPolicy': 'Background', 'gracePeriodSeconds': 5},
            json.loads(request['body']),
        )

    def test_delete_without_body_omits_content_type(self):
        self.server.response_status = 200

        self.api.delete_namespaced_job(name='x', namespace='n')

        request = self.server.requests[-1]
        self.assertEqual(b'', request['body'])
        self.assertIsNone(request['content_type'])
        self.assertIsNone(request['content_types'])

    def test_explicit_headers_override_the_json_default(self):
        self.api.create_namespaced_job(
            namespace='n',
            body=JOB_BODY,
            _headers={'Content-Type': 'application/merge-patch+json'},
        )

        request = self.server.requests[-1]
        self.assertEqual(
            ['application/merge-patch+json'], request['content_types'],
        )

    def test_lowercase_header_is_a_single_content_type_on_the_wire(self):
        self.api.create_namespaced_job(
            namespace='n',
            body=JOB_BODY,
            _headers={'content-type': 'application/json'},
        )

        request = self.server.requests[-1]
        self.assertEqual(['application/json'], request['content_types'])
